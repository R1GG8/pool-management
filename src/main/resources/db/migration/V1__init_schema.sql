CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    phone VARCHAR(32) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE reservations (
    id UUID PRIMARY KEY,
    client_id BIGINT NOT NULL,
    reserved_time TIMESTAMP NOT NULL,
    status VARCHAR(20) DEFAULT 'ACTIVE' NOT NULL,
    cancel_reason TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT fk_reservations_client
        FOREIGN KEY (client_id) REFERENCES clients(id) ON DELETE RESTRICT
);

CREATE INDEX idx_reservations_time_status
    ON reservations (reserved_time, status);

CREATE UNIQUE INDEX idx_client_slot_unique
    ON reservations (client_id, reserved_time)
    WHERE status = 'ACTIVE';